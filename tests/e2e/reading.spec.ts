import { test, expect } from '@playwright/test';
import { epubFixture, pdfFixture, txtFixture } from '../fixtures';
test('imports TXT, EPUB and PDF, persists notes, restores progress and supports mobile', async ({ page, request }) => {
    const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('/');
    await expect(page.getByRole('button', { name: '导入第一本书' })).toBeVisible();
    await page.getByRole('button', { name: '导入第一本书' }).click();
    await page.locator('input[type=file]').setInputFiles({ name: '浏览器阅读验收.txt', mimeType: 'text/plain', buffer: Buffer.from(txtFixture) });
    await expect(page.getByRole('heading', { name: '第一章 记忆' })).toBeVisible();
    const p = page.locator('[data-passage]').first();
    await p.click();
    await page.waitForTimeout(700);
    await page.getByRole('button', { name: '添加书签', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('书签已保存');
    await p.evaluate(el => { const range = document.createRange(); range.selectNodeContents(el.firstChild!); const s = window.getSelection()!; s.removeAllRanges(); s.addRange(range); });
    await p.dispatchEvent('mouseup');
    await expect(page.getByRole('button', { name: '高亮', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '高亮', exact: true }).click();
    await page.getByRole('button', { name: '批注', exact: true }).click();
    await page.getByRole('textbox', { name: '笔记内容' }).fill('浏览器端持久化笔记');
    await page.getByRole('button', { name: '保存笔记', exact: true }).click();
    await page.getByRole('button', { name: '取消选文' }).click();
    await page.getByRole('button', { name: '下一章', exact: true }).click();
    await expect(page.getByRole('heading', { name: '第二章 未读' })).toBeVisible();
    await page.locator('[data-passage]').first().click();
    await page.waitForTimeout(700);
    await page.reload();
    await expect(page.getByRole('heading', { name: '第二章 未读' })).toBeVisible();
    await page.getByRole('button', { name: '笔记', exact: true }).first().click();
    await expect(page.getByText('浏览器端持久化笔记', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: '一起读懂这一段' }).click();
    await expect(page.getByRole('status')).toContainText('API Key');
    const epub = await request.post('/api/books', { multipart: { files: { name: 'engine.epub', mimeType: 'application/epub+zip', buffer: await epubFixture() } } });
    expect(epub.ok()).toBeTruthy();
    const er = (await epub.json())[0];
    expect(er.error).toBeUndefined();
    const pdf = await request.post('/api/books', { multipart: { files: { name: 'engine.pdf', mimeType: 'application/pdf', buffer: pdfFixture() } } });
    expect(pdf.ok()).toBeTruthy();
    const pr = (await pdf.json())[0];
    expect(pr.error).toBeUndefined();
    await page.reload();
    await page.getByRole('button', { name: '知间 · 我的书房' }).click();
    await expect(page.getByText('Between Pages · EPUB fixture', { exact: true }).first()).toBeVisible();
    await page.getByRole('button', { name: 'Between Pages · EPUB fixture', exact: true }).last().click();
    await expect(page.getByRole('heading', { name: 'Chapter One' })).toBeVisible();
    await page.getByRole('button', { name: 'EPUB 原版' }).click();
    await expect(page.locator('.original-host iframe')).toBeVisible();
    await expect(page.frameLocator('.original-host iframe').getByText('Memory is not a fixed archive.',{exact:false})).toBeVisible();
    await expect.poll(async()=>((await (await request.get(`/api/books/${er.id}/progress`)).json()).location||'').startsWith('epubcfi(')).toBeTruthy();
    await page.getByRole('button', { name: '知间 · 我的书房' }).click();
    await page.getByRole('button', { name: 'engine', exact: true }).last().click();
    await expect(page.getByRole('heading', { name: '第 1 页' })).toBeVisible();
    await page.getByRole('button', { name: 'PDF 原版' }).click();
    await expect(page.getByLabel('PDF 第 1 页')).toBeVisible();
    await page.waitForTimeout(1000);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.locator('.mobile-nav')).toBeVisible();
    await page.getByRole('button', { name: '目录', exact: true }).last().click();
    await page.getByRole('button', { name: '02 第 2 页' }).click();
    await expect(page.getByRole('heading', { name: '第 2 页' })).toBeVisible();
    await page.getByRole('button', { name: '教授', exact: true }).click();
    await expect(page.getByRole('button', { name: 'AI 教授', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '收起面板' }).click();
    await page.screenshot({ path: 'test-results/mobile-reader.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '文本视图' }).click();
    await page.screenshot({ path: 'test-results/desktop-reader.png', fullPage: true });
    const backup = await request.get('/api/backup');
    expect(backup.ok()).toBeTruthy();
    expect((await backup.body()).length).toBeGreaterThan(1000);
    expect(errors).toEqual([]);
});
